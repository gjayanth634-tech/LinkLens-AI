"""
Model evaluation and comparison utilities for LinkLens AI.
Calculates performance metrics (accuracy, precision, recall, f1, ROC-AUC, confusion matrix)
and produces formatted evaluation reports.
"""

from typing import Dict, List, Any, Optional
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    confusion_matrix,
)


def evaluate_model(model: Any, X_test: Any, y_test: Any, model_name: str) -> Dict[str, Any]:
    """
    Evaluate a machine learning model on test data and calculate performance metrics.

    Args:
        model: Trained classifier supporting predict (and optionally predict_proba).
        X_test: Test feature matrix.
        y_test: True ground truth labels (0=legitimate, 1=phishing).
        model_name: Display name of the model.

    Returns:
        dict: Performance metrics including accuracy, precision, recall, f1, roc_auc,
              and confusion matrix formatted as a list of lists.
    """
    y_pred = model.predict(X_test)

    acc = accuracy_score(y_test, y_pred)
    prec = precision_score(y_test, y_pred, zero_division=0)
    rec = recall_score(y_test, y_pred, zero_division=0)
    f1 = f1_score(y_test, y_pred, zero_division=0)

    roc_auc: Optional[float] = None
    if hasattr(model, "predict_proba"):
        try:
            probabilities = model.predict_proba(X_test)
            if probabilities.ndim == 2 and probabilities.shape[1] > 1:
                # Class 1 probability
                roc_auc = float(roc_auc_score(y_test, probabilities[:, 1]))
            else:
                roc_auc = float(roc_auc_score(y_test, probabilities))
        except Exception as exc:
            print(f"[Warning] Failed to calculate ROC-AUC for {model_name}: {exc}")
            roc_auc = None
    elif hasattr(model, "decision_function"):
        try:
            scores = model.decision_function(X_test)
            roc_auc = float(roc_auc_score(y_test, scores))
        except Exception:
            roc_auc = None

    cm = confusion_matrix(y_test, y_pred).tolist()

    return {
        "model_name": model_name,
        "accuracy": round(float(acc), 4),
        "precision": round(float(prec), 4),
        "recall": round(float(rec), 4),
        "f1_score": round(float(f1), 4),
        "roc_auc": round(float(roc_auc), 4) if roc_auc is not None else None,
        "confusion_matrix": cm,
    }


def compare_models(results: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Compare multiple evaluation metric dictionaries and identify the top performer.

    Args:
        results: List of evaluation dictionaries generated by evaluate_model.

    Returns:
        dict: Summary containing list of evaluated models and details of the best model.
    """
    if not results:
        return {
            "models": [],
            "best_model": None,
            "best_model_details": None,
            "comparison_metric": "f1_score",
        }

    # Best model prioritized primarily by F1-score, secondarily by accuracy and ROC-AUC
    best = max(
        results,
        key=lambda r: (
            r.get("f1_score", 0.0),
            r.get("accuracy", 0.0),
            r.get("roc_auc") if r.get("roc_auc") is not None else 0.0,
        ),
    )

    return {
        "models": results,
        "best_model": best["model_name"],
        "best_model_details": best,
        "comparison_metric": "f1_score",
    }


def format_evaluation_report(results: Dict[str, Any]) -> str:
    """
    Format evaluation or comparison results into a clean, human-readable text report.

    Args:
        results: Single model evaluation dict or comparison dict containing 'models'.

    Returns:
        str: Formatted report text.
    """
    # Check if this is a comparison dictionary
    if "models" in results and isinstance(results["models"], list):
        lines = [
            "=" * 60,
            "           LINKLENS AI - MODEL COMPARISON REPORT",
            "=" * 60,
            f"{'Model Name':<20} | {'Accuracy':<9} | {'Precision':<9} | {'Recall':<8} | {'F1-Score':<8} | {'ROC-AUC':<8}",
            "-" * 72,
        ]
        for m in results["models"]:
            roc_str = f"{m.get('roc_auc', 'N/A'):.4f}" if m.get("roc_auc") is not None else "N/A"
            lines.append(
                f"{m.get('model_name', 'Unknown'):<20} | "
                f"{m.get('accuracy', 0.0):<9.4f} | "
                f"{m.get('precision', 0.0):<9.4f} | "
                f"{m.get('recall', 0.0):<8.4f} | "
                f"{m.get('f1_score', 0.0):<8.4f} | "
                f"{roc_str:<8}"
            )
        lines.append("-" * 72)
        lines.append(f"Recommended Model: {results.get('best_model', 'N/A')} (based on highest {results.get('comparison_metric', 'f1_score')})")
        lines.append("=" * 60)
        return "\n".join(lines)

    # Single model report
    model_name = results.get("model_name", "Model")
    accuracy = results.get("accuracy", 0.0)
    precision = results.get("precision", 0.0)
    recall = results.get("recall", 0.0)
    f1 = results.get("f1_score", 0.0)
    roc_auc = results.get("roc_auc")
    roc_str = f"{roc_auc:.4f}" if roc_auc is not None else "N/A"
    cm = results.get("confusion_matrix", [[0, 0], [0, 0]])

    tn = cm[0][0] if len(cm) > 0 and len(cm[0]) > 0 else 0
    fp = cm[0][1] if len(cm) > 0 and len(cm[0]) > 1 else 0
    fn = cm[1][0] if len(cm) > 1 and len(cm[1]) > 0 else 0
    tp = cm[1][1] if len(cm) > 1 and len(cm[1]) > 1 else 0

    lines = [
        "=" * 50,
        f"       EVALUATION REPORT: {model_name.upper()}",
        "=" * 50,
        f"  Accuracy:         {accuracy:.4f} ({accuracy * 100:.2f}%)",
        f"  Precision:        {precision:.4f} ({precision * 100:.2f}%)",
        f"  Recall:           {recall:.4f} ({recall * 100:.2f}%)",
        f"  F1-Score:         {f1:.4f}",
        f"  ROC-AUC:          {roc_str}",
        "-" * 50,
        "  Confusion Matrix:",
        f"    True Negative (Legitimate):  {tn}",
        f"    False Positive (Type I):     {fp}",
        f"    False Negative (Type II):    {fn}",
        f"    True Positive (Phishing):    {tp}",
        "=" * 50,
    ]
    return "\n".join(lines)
